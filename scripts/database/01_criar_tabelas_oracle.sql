    RADIACAO_SOLAR_MEDIA NUMBER(10, 2),
    RISCO_HIDRICO_SCORE NUMBER(5, 2),
    RISCO_INUNDACAO_SCORE NUMBER(5, 2),
    SENSIBILIDADE_SCORE NUMBER(5, 2),
    DEMANDA_REFRIG_SCORE NUMBER(5, 2),
    AREA_CAPTACAO_M2 NUMBER(12, 2),
    CAPACIDADE_RESERVATORIO_L NUMBER(12, 2),
    CONSUMO_AGUA_M3_DIA NUMBER(10, 2),
    EFICIENCIA_CAPTACAO_PCT NUMBER(5, 2),
    POTENCIAL_PLUVIAL_M3_ANO NUMBER(12, 2),
    CONECTIVIDADE_SCORE NUMBER(5, 2),
    REDUNDANCIA_SCORE NUMBER(5, 2),
    ENERGIA_SCORE NUMBER(5, 2),
    RISCO_ROTA_UNICA_SCORE NUMBER(5, 2),
    RESILIENCIA_SCORE NUMBER(5, 2),
    ORIGEM_RISCO_HIDRICO VARCHAR2(40),
    ORIGEM_RISCO_INUNDACAO VARCHAR2(40),
    ORIGEM_SENSIBILIDADE VARCHAR2(40),
    ORIGEM_REUSO_PLUVIAL VARCHAR2(40),
    ORIGEM_INFRA_DIGITAL VARCHAR2(40),
    ORIGEM_DEMANDA_REFRIG VARCHAR2(40),
