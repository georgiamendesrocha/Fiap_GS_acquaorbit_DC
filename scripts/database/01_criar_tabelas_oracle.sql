    CONSTRAINT CK_AO_IND_EFICIENCIA
        CHECK (EFICIENCIA_CAPTACAO_PCT BETWEEN 0 AND 100),
    CONSTRAINT CK_AO_IND_CONECT
        CHECK (CONECTIVIDADE_SCORE BETWEEN 0 AND 10),
    CONSTRAINT CK_AO_IND_REDUND
        CHECK (REDUNDANCIA_SCORE BETWEEN 0 AND 10),
    CONSTRAINT CK_AO_IND_ENERGIA
        CHECK (ENERGIA_SCORE BETWEEN 0 AND 10),
    CONSTRAINT CK_AO_IND_ROTA
        CHECK (RISCO_ROTA_UNICA_SCORE BETWEEN 0 AND 10),
    CONSTRAINT CK_AO_IND_RESIL
