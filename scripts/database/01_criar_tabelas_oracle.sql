CREATE TABLE AO_REGIOES (
    REGIAO_ID VARCHAR2(80) PRIMARY KEY,
    REGIAO VARCHAR2(180) NOT NULL,
    EIXO_REGIONAL VARCHAR2(180),
    CIDADE VARCHAR2(100) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    LATITUDE NUMBER(9, 6) NOT NULL,
    LONGITUDE NUMBER(9, 6) NOT NULL,
    CONTEXTO_TERRITORIAL VARCHAR2(500),
    BIOMA_CONTEXTO VARCHAR2(120),
    PERIODO_REFERENCIA NUMBER(4),
    FONTE_CLIMATICA VARCHAR2(80),
    FONTE_CLIMATICA_URL VARCHAR2(300),
    ORIGEM_DADOS_CLIMATICOS VARCHAR2(40),
    CONSTRAINT CK_AO_REG_ESTADO
        CHECK (ESTADO IN ('SP', 'RJ', 'PR')),
    CONSTRAINT CK_AO_REG_LAT
        CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_AO_REG_LON
        CHECK (LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_AO_REG_ORIG_CLIMA
        CHECK (ORIGEM_DADOS_CLIMATICOS IN ('real', 'simulado', 'inspirado', 'calculado', 'parametrizado', 'calculado e simulado'))
);

